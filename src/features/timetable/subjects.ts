// 좁은 주간 표에서 쓸 과목 줄임말. 학생들이 실제로 부르는 이름 기준.
const SHORT: [RegExp, string][] = [
  [/^생명과학/, '생명'],
  [/^물리학/, '물리'],
  [/^지구과학/, '지구'],
  [/^확률과\s?통계/, '확통'],
  [/^미적분/, '미적'],
  [/^사회\s?·?\s?문화/, '사문'],
  [/^생활과\s?윤리/, '생윤'],
  [/^윤리와\s?사상/, '윤사'],
  [/^한국지리/, '한지'],
  [/^세계지리/, '세지'],
  [/^동아시아사/, '동아사'],
  [/^정치와\s?법/, '정법'],
  [/^언어와\s?매체/, '언매'],
  [/^화법과\s?작문/, '화작'],
  [/^영어\s?독해와\s?작문/, '영독작'],
  [/^창의적\s?체험활동/, '창체'],
];

/** '생명과학Ⅰ' → '생명Ⅰ'. 줄일 규칙이 없으면 그대로. */
export function shortSubject(name: string) {
  for (const [re, short] of SHORT) {
    const m = name.match(re);
    if (m) return short + name.slice(m[0].length).trim();
  }
  return name;
}
